uint8_t autosar_crc8_sae_j1850(const uint8_t *data, size_t length) {
    uint8_t crc = 0xFF;
    for (size_t i = 0; i < length; i++) {
        crc = crc8_table[crc ^ data[i]];
    }
    return crc ^ 0xFF;
}

uint32_t autosar_e2e_crc32(uint16_t data_id, const uint8_t *payload, size_t length) {
    uint32_t crc = 0xFFFFFFFFU;
    
    /* Prepend 16-bit Data ID (Anti-Masquerade protection) via lookup table */
    crc = (crc >> 8) ^ crc32_autosar_table[(crc ^ (data_id & 0xFF)) & 0xFF];
    crc = (crc >> 8) ^ crc32_autosar_table[(crc ^ ((data_id >> 8) & 0xFF)) & 0xFF];

    /* Fast table-driven payload processing */
    if (payload && length > 0) {
        for (size_t i = 0; i < length; i++) {
            crc = (crc >> 8) ^ crc32_autosar_table[(crc ^ payload[i]) & 0xFF];
        }
    }
    return ~crc;
}

e2e_status_t autosar_e2e_protect_verify(
    e2e_channel_state_t *channel,
    uint16_t packet_data_id,
    uint8_t  rolling_counter,
    uint32_t transmitted_crc,
    const uint8_t *payload,
    size_t length
) {
    if (!channel) return E2E_STATUS_DATA_CORRUPTED;
    if (!payload && length > 0) return E2E_STATUS_DATA_CORRUPTED;

    /* 1. Anti-Masquerade verification */
    if (packet_data_id != channel->data_id) {
        return E2E_STATUS_WRONG_DATA_ID;
    }

    /* 2. Fast Table CRC-32 verification */
    uint32_t expected_crc = autosar_e2e_crc32(channel->data_id, payload, length);
    if (expected_crc != transmitted_crc) {
        return E2E_STATUS_DATA_CORRUPTED;
    }

    /* 3. Handle First Frame Sync */
    uint8_t current_counter = rolling_counter & 0x0F;
    if (!channel->initialized) {
        channel->last_counter = current_counter;
        channel->initialized = true;
        return E2E_STATUS_INITIALIZING;
    }

    /* 4. Detect Replay Attack / Freeze */
    if (current_counter == channel->last_counter) {
        return E2E_STATUS_REPEATED;
    }

    /* 5. Modulo-16 Arithmetic Jump Calculation */
    int16_t delta = (int16_t)(current_counter - channel->last_counter);
    if (delta < 0) {
        delta += 16;
    }

    /* 6. Verify Packet Loss Boundary */
    if (delta > (int16_t)channel->max_counter_jump) {
        channel->last_counter = current_counter;
        return E2E_STATUS_SEQUENCE_LOSS;
    }

    channel->last_counter = current_counter;
    return E2E_STATUS_OK;
}

uint32_t autosar_e2e_status_to_violation(e2e_status_t status) {
    switch (status) {
        case E2E_STATUS_OK:
        case E2E_STATUS_INITIALIZING:
            return 0x00000000U; /* VIOLATION_NONE */
        case E2E_STATUS_DATA_CORRUPTED:
            return 0x00001004U; /* VIOLATION_CRC_CORRUPTED -> Immediate E-STOP */
        case E2E_STATUS_REPEATED:
        case E2E_STATUS_SEQUENCE_LOSS:
            return 0x00001003U; /* VIOLATION_DEADLINE_MISS / Sequence Loss */
        case E2E_STATUS_WRONG_DATA_ID:
        default:
            return 0x00001005U; /* VIOLATION_PLAUSIBILITY / Masquerade Fault */
    }
}
